"""Generate small public resource vectors from hash-pinned cold inventory."""
import hashlib,json
from pathlib import Path
k=Path(__file__).resolve().parent
p=k/'vectors.h'
assert not p.exists()
r=json.loads((k/'inputs.json').read_text())
lines=['/* Generated by make-vectors.py from inputs.json. No hive data beyond SMBus resources. */']
for profile in ('physical220','emulator004'):
    for value,suffix in (('BasicConfigVector','basic'),('BootConfig','boot')):
        b=bytes.fromhex(r['fixtures'][profile]['values'][value]['hex'])
        lines.append('static const unsigned char '+profile+'_'+suffix+'[] = {')
        lines.extend('    '+','.join('0x%02x'%v for v in b[i:i+16])+',' for i in range(0,len(b),16))
        lines.append('};')
p.write_bytes(('\n'.join(lines)+'\n').encode())
print('Generated four resource vectors; inputs SHA256 '+hashlib.sha256((k/'inputs.json').read_bytes()).hexdigest())
